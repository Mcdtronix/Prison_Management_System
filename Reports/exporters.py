"""CSV, Excel and PDF output for a prepared report."""
from __future__ import annotations

import csv
import datetime
import re
from io import BytesIO, StringIO

from django.http import HttpResponse

from .engine import EXPORT_MAX_ROWS, PreparedReport, describe_filters, rows


def _esc(value):
    """Text safe for ReportLab paragraphs (which parse a little markup)."""
    return str(value).replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def _filename(title, ext):
    stem = re.sub(r"[^A-Za-z0-9_-]+", "_", title).strip("_") or "report"
    return f"{stem}_{datetime.date.today():%Y%m%d}.{ext}"


def _meta(report: PreparedReport, title, user, station, total):
    generated = datetime.datetime.now().strftime("%d/%m/%Y %H:%M")
    shown = min(total, EXPORT_MAX_ROWS)
    lines = [
        ("Report", title),
        ("Source", report.source.label),
        ("Generated by", getattr(user, "get_full_name", lambda: "")() or user.username),
        ("Station / scope", station or "All stations"),
        ("Generated on", generated),
        ("Filters", describe_filters(report)),
        ("Records", f"{shown} of {total}" if total > shown else str(total)),
    ]
    return lines


def to_csv(report, title, user, station, total):
    buffer = StringIO()
    writer = csv.writer(buffer)
    writer.writerow(report.labels())
    for row in rows(report, limit=EXPORT_MAX_ROWS):
        writer.writerow(row)
    # BOM so Excel opens UTF-8 names correctly.
    response = HttpResponse("﻿" + buffer.getvalue(), content_type="text/csv; charset=utf-8")
    response["Content-Disposition"] = f'attachment; filename="{_filename(title, "csv")}"'
    return response


def to_excel(report, title, user, station, total):
    import openpyxl
    from openpyxl.styles import Alignment, Font, PatternFill
    from openpyxl.utils import get_column_letter

    wb = openpyxl.Workbook()
    ws = wb.active
    ws.title = "Report"[:31]

    ws.append([title])
    ws["A1"].font = Font(bold=True, size=14, color="0B4F2A")
    for label, value in _meta(report, title, user, station, total)[1:]:
        ws.append([label, value])
        ws.cell(row=ws.max_row, column=1).font = Font(bold=True, color="555555")
    ws.append([])

    header_row = ws.max_row + 1
    ws.append(report.labels())
    header_fill = PatternFill("solid", fgColor="0B4F2A")
    for cell in ws[header_row]:
        cell.font = Font(bold=True, color="FFFFFF")
        cell.fill = header_fill
        cell.alignment = Alignment(vertical="center")

    widths = [len(label) for label in report.labels()]
    for row in rows(report, limit=EXPORT_MAX_ROWS, raw=True):
        ws.append(row)
        for i, value in enumerate(row):
            widths[i] = min(max(widths[i], len(str(value))), 60)

    for i, column in enumerate(report.columns, start=1):
        letter = get_column_letter(i)
        ws.column_dimensions[letter].width = widths[i - 1] + 3
        if column.type == "date":
            for cell in ws[letter][header_row:]:
                cell.number_format = "DD/MM/YYYY"

    ws.freeze_panes = ws.cell(row=header_row + 1, column=1)
    if ws.max_row > header_row:
        ws.auto_filter.ref = f"A{header_row}:{get_column_letter(len(report.columns))}{ws.max_row}"

    out = BytesIO()
    wb.save(out)
    response = HttpResponse(
        out.getvalue(), content_type="application/vnd.openxmlformats-officedocument.spreadsheetml.sheet"
    )
    response["Content-Disposition"] = f'attachment; filename="{_filename(title, "xlsx")}"'
    return response


def to_pdf(report, title, user, station, total):
    from reportlab.lib import colors
    from reportlab.lib.pagesizes import A4, landscape
    from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
    from reportlab.lib.units import mm
    from reportlab.platypus import LongTable, Paragraph, SimpleDocTemplate, Spacer, TableStyle

    green = colors.HexColor("#0B4F2A")
    gold = colors.HexColor("#D7A928")
    styles = getSampleStyleSheet()
    cell = ParagraphStyle("cell", parent=styles["BodyText"], fontSize=7.5, leading=9)
    head = ParagraphStyle("head", parent=cell, textColor=colors.white, fontName="Helvetica-Bold")
    meta = ParagraphStyle("meta", parent=styles["BodyText"], fontSize=8, leading=10, textColor=colors.HexColor("#444444"))

    buffer = BytesIO()
    page = landscape(A4)
    doc = SimpleDocTemplate(buffer, pagesize=page, leftMargin=12 * mm, rightMargin=12 * mm,
                            topMargin=14 * mm, bottomMargin=14 * mm, title=title)

    def decorate(canvas, document):
        canvas.saveState()
        canvas.setStrokeColor(gold)
        canvas.setLineWidth(1.2)
        canvas.line(12 * mm, page[1] - 9 * mm, page[0] - 12 * mm, page[1] - 9 * mm)
        canvas.setFont("Helvetica", 7)
        canvas.setFillColor(colors.HexColor("#666666"))
        canvas.drawString(12 * mm, 7 * mm, "PrisonMS · Official use only")
        canvas.drawRightString(page[0] - 12 * mm, 7 * mm, f"Page {document.page}")
        canvas.restoreState()

    elements = [Paragraph(_esc(title), ParagraphStyle("title", parent=styles["Title"], textColor=green, alignment=0, fontSize=16))]
    for label, value in _meta(report, title, user, station, total)[1:]:
        elements.append(Paragraph(f"<b>{label}:</b> {_esc(value)}", meta))
    elements.append(Spacer(1, 6))

    data = [[Paragraph(label, head) for label in report.labels()]]
    for row in rows(report, limit=EXPORT_MAX_ROWS):
        data.append([Paragraph(_esc(value), cell) for value in row])

    usable = page[0] - 24 * mm
    table = LongTable(data, repeatRows=1, colWidths=[usable / len(report.columns)] * len(report.columns))
    table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), green),
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, colors.HexColor("#F3F6F4")]),
        ("LINEBELOW", (0, 0), (-1, -1), 0.25, colors.HexColor("#D0D7D3")),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 3),
        ("TOPPADDING", (0, 0), (-1, -1), 3),
    ]))
    elements.append(table)
    doc.build(elements, onFirstPage=decorate, onLaterPages=decorate)

    response = HttpResponse(buffer.getvalue(), content_type="application/pdf")
    response["Content-Disposition"] = f'attachment; filename="{_filename(title, "pdf")}"'
    return response


EXPORTERS = {"csv": to_csv, "excel": to_excel, "pdf": to_pdf}
